//////////////////////////////////////////////////////////////////////////////////
// File Name   : distance_controller.v
// Project     : FPGA Mecanum Robot Chassis
//
// Description :
//   定距离直线运动控制器
//
// 当前第一版：
//   收到 ASCII 'F' (0x46)
//   -> 记录当前X位置
//   -> 前进500mm
//   -> 接近目标自动减速
//   -> 到达目标自动停车
//
// 粗标定：
//   6308 count ≈ 1000 mm
//
// 因此：
//   500 mm ≈ 3154 count
//////////////////////////////////////////////////////////////////////////////////

module distance_controller #(

    //================================================
    // 目标距离
    //
    // 6308 count = 1000 mm
    // 3154 count = 500 mm
    //================================================
    parameter signed [31:0] TARGET_COUNT =
        32'sd3154,

    //================================================
    // 距离目标还剩约100mm时减速
    //
    // 100mm ≈ 631 count
    //================================================
    parameter signed [31:0] SLOW_ZONE_COUNT =
        32'sd630,

    //================================================
    // 提前停车补偿
    //
    // 80 count ≈ 12.7mm
    //
    // 考虑小车惯性
    // 后面根据实际停车距离继续调整
    //================================================
    parameter signed [31:0] STOP_EARLY_COUNT =
        32'sd80,

    //================================================
    // 正常速度
    //================================================
    parameter signed [12:0] FAST_SPEED =
        13'sd32,

    //================================================
    // 减速速度
    //================================================
    parameter signed [12:0] SLOW_SPEED =
        13'sd16

)(
    input wire clk,
    input wire reset_n,

    // 10ms控制周期
    input wire sample_tick,

    //================================================
    // UART
    //================================================

    input wire [7:0] rx_data,
    input wire       rx_done,
    //================================================
    // 外部状态机控制接口
    //================================================

    input wire ext_start,
    input wire ext_stop,
    //================================================
    // IMU校准完成
    //================================================

    input wire calib_done,

    //================================================
    // 当前里程计X位置
    // 单位：count
    //================================================

    input wire signed [31:0] pos_x_count,

    //================================================
    // car_cmd原来的手动控制量
    //================================================

    input wire signed [12:0] manual_vx,
    input wire signed [12:0] manual_vy,
    input wire signed [12:0] manual_wz,

    //================================================
    // 最终给底盘的控制量
    //================================================

    output reg signed [12:0] vx_out,
    output reg signed [12:0] vy_out,
    output reg signed [12:0] wz_out,

    //================================================
    // 调试
    //================================================

    output reg auto_active,
    output reg auto_done
);


    //================================================
    // 任务开始时的位置
    //================================================

    reg signed [31:0] start_x;


    //================================================
    // 自动模式当前速度
    //================================================

    reg signed [12:0] auto_vx;


    //================================================
    // 已经前进的距离
    //================================================

    wire signed [31:0] travelled_count;

    assign travelled_count =
        pos_x_count - start_x;


    //================================================
    // 开始减速的位置
    //
    // 3154 - 630 = 2524
    //================================================

    wire signed [31:0] slow_start_count;

    assign slow_start_count =
        TARGET_COUNT - SLOW_ZONE_COUNT;


    //================================================
    // 实际停车判断点
    //
    // 3154 - 80 = 3074
    //================================================

    wire signed [31:0] stop_count;

    assign stop_count =
        TARGET_COUNT - STOP_EARLY_COUNT;


    //================================================
    // 输出选择
    //================================================

    always @(*) begin

        //============================================
        // 自动定距正在运行
        //============================================

        if(auto_active) begin

            vx_out = auto_vx;

            vy_out = 13'sd0;

            // 不允许用户直接旋转
            // Heading Hold自己产生Wz修正
            wz_out = 13'sd0;

        end


        //============================================
        // 自动任务完成
        //
        // 保持停车
        // 防止car_cmd中的F继续让小车前进
        //============================================

        else if(auto_done) begin

            vx_out = 13'sd0;
            vy_out = 13'sd0;
            wz_out = 13'sd0;

        end


        //============================================
        // 普通手动模式
        //============================================

        else begin

            vx_out = manual_vx;
            vy_out = manual_vy;
            wz_out = manual_wz;

        end

    end


    //================================================
    // 定距离状态控制
    //================================================

 //================================================
// 定距离状态控制
//================================================

always @(posedge clk or negedge reset_n) begin

    if(!reset_n) begin

        start_x <= 32'sd0;

        auto_vx <= 13'sd0;

        auto_active <= 1'b0;

        auto_done <= 1'b0;

    end

    else begin

        //================================================
        // 停止
        //
        // ext_stop = 状态机停止
        // S = UART手动停止
        //================================================

        if(
            ext_stop
            ||
            (
                rx_done
                &&
                (rx_data == 8'h53)
            )
        ) begin

            auto_active <= 1'b0;

            auto_done <= 1'b0;

            auto_vx <= 13'sd0;

        end


        //================================================
        // 开始一次定距离任务
        //
        // ext_start = 状态机启动
        // F = UART手动启动
        //================================================

        else if(
            (
                ext_start
                ||
                (
                    rx_done
                    &&
                    (rx_data == 8'h46)
                )
            )
            &&
            calib_done
            &&
            !auto_active
        ) begin

            // 保存当前起点
            start_x <= pos_x_count;

            // 开始运行
            auto_active <= 1'b1;

            auto_done <= 1'b0;

            auto_vx <= FAST_SPEED;

        end


        //================================================
        // 自动运行
        //================================================

        else if(
            auto_active
            &&
            sample_tick
        ) begin


            //============================================
            // 到达停车位置
            //============================================

            if(
                travelled_count
                >=
                stop_count
            ) begin

                auto_vx <= 13'sd0;

                auto_active <= 1'b0;

                auto_done <= 1'b1;

            end


            //============================================
            // 进入减速区
            //============================================

            else if(
                travelled_count
                >=
                slow_start_count
            ) begin

                auto_vx <= SLOW_SPEED;

            end


            //============================================
            // 正常运行
            //============================================

            else begin

                auto_vx <= FAST_SPEED;

            end

        end

    end

end
endmodule